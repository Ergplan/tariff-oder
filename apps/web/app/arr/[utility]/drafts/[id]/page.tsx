import Link from "next/link";
import type { FilingDraftOut } from "@tariff/contracts";
import { apiTry } from "@/lib/api";
import { ErrorBanner } from "../../../../components";

export const dynamic = "force-dynamic";

type Entry = { id: string; where: string; kind: string; value: string; unit: string | null; origin: Record<string, unknown> };

/**
 * One filing draft (ADR-0018): the watermark, the downloads (DOCX narrative, XLSX formats)
 * and the trace annex — every number in the draft with its origin.  A draft is never filed:
 * there is no submit, e-mail or upload anywhere in the application.
 */
export default async function DraftPage({ params }: { params: Promise<{ utility: string; id: string }> }) {
  const { utility, id } = await params;
  const code = decodeURIComponent(utility);
  const res = await apiTry<FilingDraftOut>(`/arr/drafts/${encodeURIComponent(id)}`);
  if (res.error || !res.data) {
    return (
      <>
        <h1>Filing draft</h1>
        <ErrorBanner error={res.error!} />
      </>
    );
  }
  const d = res.data;
  const trace = d.trace as { numbers: number; by_kind: Record<string, number>; entries: Entry[] };
  return (
    <>
      <p>
        {d.formulation_id ? (
          <Link href={`/arr/${encodeURIComponent(code)}/formulations/${d.formulation_id}`}>← formulation</Link>
        ) : (
          <Link href={`/client/cases/${d.case_id}`}>← case</Link>
        )}
      </p>
      <h1>
        Draft petition · {code}{" "}
        {d.is_fixture ? (
          <span className="badge" data-tone="fixture">
            FIXTURE
          </span>
        ) : null}
      </h1>
      <div className="banner" data-tone="warn" role="note">
        <strong>{d.watermark}</strong>
        <div>Edit the draft, check every number against its trace, and file it yourself. This application does not file, e-mail or upload petitions.</div>
      </div>
      <p className="muted">
        Template {d.template_id} v{d.template_version} ({d.template_status}) · generated by {d.generated_by} on {new Date(d.generated_at).toLocaleString()} · {trace.numbers} numbers traced (
        {Object.entries(trace.by_kind)
          .map(([k, v]) => `${v} ${k}`)
          .join(", ")}
        )
      </p>
      {d.template_status !== "confirmed" ? (
        <div className="banner" data-tone="neutral">
          The template is <strong>{d.template_status}</strong>: its formats are not yet confirmed against the formats the commission&apos;s regulations prescribe.
        </div>
      ) : null}
      <p>
        <a href={`/api/arr/drafts/${d.id}/petition.docx`}>Download narrative (DOCX)</a> · <a href={`/api/arr/drafts/${d.id}/formats.xlsx`}>Download formats (XLSX)</a>
      </p>
      <h2>Trace annex</h2>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Trace</th>
              <th>Where</th>
              <th>Kind</th>
              <th>Value</th>
              <th>Origin</th>
            </tr>
          </thead>
          <tbody>
            {trace.entries.map((e) => (
              <tr key={e.id}>
                <td className="mono">{e.id}</td>
                <td className="mono">{e.where}</td>
                <td>
                  <span className="badge" data-tone={e.kind === "fact" ? "ok" : e.kind === "projection" || e.kind === "variance" ? "warn" : "neutral"}>
                    {e.kind}
                  </span>
                </td>
                <td className="mono">
                  {e.value} <span className="muted">{e.unit}</span>
                </td>
                <td className="muted">{origin(e)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}

function origin(e: Entry): string {
  const o = e.origin as Record<string, string | number | null>;
  if (typeof o.words === "string") return o.words; // true-up and APR drafts carry their own words
  if (e.kind === "fact") return `${o.line_code} ${o.fiscal_year} ${o.value_type} — ${o.order}, p.${o.page}: "${o.excerpt}"`;
  if (e.kind === "assumption") return `${o.key} — ${o.source_kind === "regulation_clause" ? "regulation clause" : "user"} (${o.entered_by}): ${o.rationale}`;
  return `${o.line_code} ${o.fiscal_year} — ${o.formula_words}`;
}
